  // 【它给的是什么决策】
  //   赤月期间：妖物跑得更快（×1.20）、每波刷得更多（×1.3），
  //   但**经验球价值也涨（×1.3）**。
  //   于是玩家每次都要在同一个岔路口做选择：
  //   「顶着怪潮清——经验翻倍，可能被围死」还是「先拉开距离，等它过去」。
  //   只有压力没有收益的全局事件，玩家只会学会「躲」，那是纯惩罚；
  //   收益一挂上，同一个事件在不同血量下就有不同的正确答案。
  //
  // 【为什么必须是「纯时间函数」而不是随机抽签】
  //   它每 100 秒插一次，如果从主随机流里抽「这次来不来 / 来哪一种」，
  //   后面每一波的落点都会整体错位 —— 这和挑战者那条纪律完全相同（见 sim 的说明）。
  //   所以排期直接由 tick 算出来：可复现、两端一致、测试不用跑整局就能验。
  //   ★也因此它不接受「随机强度」：同一局第 k 次赤月的强度永远一样。
  //
  // 【为什么首次在 180 秒】
  //   教学段（前 4 波 = 120 秒）必须干净：那时候玩家只有起始武器，
  //   一上来就遇到「怪突然全部加速」，学到的是「这游戏很乱」而不是「天象会来」。
  //   180 秒 = 第 6 波，玩家通常有 2~3 件武器，正好在第一个转折点之后。
  //   ★与 CHALLENGER.startSec 同为 180 → 两者会在同一波前后脚出现。
  //     这是**故意的**：每一局到这个时点都会「同时更热闹」，形成一次明确的升级感。
  //     但两者都不消耗随机流，也不改对方的状态，不会互相污染。
  //
  // ★数值全部集中在这张表里：调节奏只改这里，逻辑一行都不用动。
  const BLOOD_MOON = {
    name: '赤月',
    // 第一次降临的时刻（秒）
    startSec: 180,
    // 之后每隔多久来一次（秒）。100 秒 ≈ 3.3 波，比一波长、比一分钟短：
    // 玩家能感觉到「又来了」，但不至于一直在里面。
    everySec: 100,
    // 每次持续（秒）。22 秒 ≈ 一波的四分之三：
    // 足够刷出「这一波是在赤月里打的」，又不够撑满一整波（下一波就恢复正常）。
    durationSec: 22,
    // 妖物移速倍率。1.20 是「逃不掉但追不上」的分界：
    // 再高（1.35）玩家就变成只能跑、完全没法清场；再低（1.10）感觉不到。
    mobSpeedMul: 1.20,
    // 每波数量的倍率。1.3 = 多三成，压力够了但不会顶破 MAX_MOBS
    // （撞到上限时 sim 的 room 裁剪会兜住，见 spawnWave）。
    countMul: 1.3,
    // 经验球价值倍率 —— 这就是「顶着清的回报」。
    expMul: 1.3
  };

  // 某个 tick 是否处在赤月之中（纯函数：测试直接调它，不用跑整局）。
  // 返回 { on, index, leftSec }：
  //   index   = 这是本局第几次赤月（0 起），-1 表示还没到第一次
  //   leftSec = 还剩几秒（不在赤月里时为 0）
  // 【为什么入参是 tick 而不是秒】秒是 tick/HZ 算出来的浮点数，
  //   用它做边界比较会出现「180.0000000001 秒算不算」，tick 是整数，边界是硬的。
  function moonPhaseAt(tick) {
    const rule = BLOOD_MOON;
    const start = Math.round(rule.startSec * TICK_HZ);
    const every = Math.round(rule.everySec * TICK_HZ);
    const dur = Math.round(rule.durationSec * TICK_HZ);
    // 参数被调坏时一律返回「没有赤月」：宁可少一个玩法，也不能让主循环里出负时长
    if (every <= 0 || dur <= 0 || !(tick >= start)) {
      return { on: false, index: -1, leftSec: 0 };
    }
    const index = Math.floor((tick - start) / every);
    const into = (tick - start) - index * every;
    if (into >= dur) return { on: false, index: index, leftSec: 0 };
    return { on: true, index: index, leftSec: (dur - into) / TICK_HZ };
  }

