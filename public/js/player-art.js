  //   ① 之前 8 个色值散在 8 个函数里，调一次配色要翻 8 个地方，漏一处就是
  //      「这个角色下半身还是旧色」——曾经就是这么改成集中的；
  //   ② 集中之后能被自检读到（tools/artshot.js 会拿它跟 const.js 的 accent、
  //      选择页立绘的主色逐角色比对，防止三个文件改漏一个）。
  //
  // 四档的含义：
  //   main —— 身体主色，也就是 const.js 的 accent 与选择页立绘的主色
  //   dark —— 斗篷 / 长袍（main 压暗，保证整个剪影是**同一个色系**）
  //   deep —— 最暗的一档（帽檐、蒙面布、皮围裙这类压在最底下的东西）
  //   soft —— 最亮的一档（头巾、盔顶、光头这类受光面）
  //
  // 色相分布（0° 红 → 顺数，避开了 250°~290° 的紫/紫蓝区）：
  //   猎魔人 5° 蜜桃珊瑚 / 铁匠 30° 焦糖拿铁 / 修女 46° 香草奶油 /
  //   苦行僧 74° 嫩芽绿 / 学者 116° 抹茶 / 盗贼 167° 薄荷青 /
  //   圣殿骑士 209° 雾天蓝 / 巫女 337° 莓果红。
