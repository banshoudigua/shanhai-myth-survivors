// public/js/player-art.js —— 战场上的角色形象（像素画风，纯前端绘制）
//
// 【为什么需要这个文件】原来战场上所有玩家都是同一张精灵（兜帽 + 斗篷 + 金腰带），
// 只有头顶名牌和脚下光环的区别。多人局里四个人挤在一起打的时候，
// 名牌会被怪、特效、伤害数字挡住 —— 玩家真正能一眼认出的只有**轮廓**。
// 这个文件让每个角色在战场上长得不一样。
//
// 【这一轮改了什么】整张画风从「程序化矢量画」换成了**像素点阵**：
// 原来是把 arc / ellipse 拼出来的圆球加眼睛，远看像表情包；现在是 16×16 的
// 点阵小人，头大身小（Q 版比例）、明快的马卡龙配色 —— 更可爱，也更像「游戏角色」。
//
// 【为什么形体比细节重要】战场上的角色只有 40 来个像素宽，脸上画不出五官、
// 手里画不清武器。所以每个角色只保留三件能在 16×16 里认出来的特征：
// 头顶饰物（兜帽 / 头巾 / 宽檐帽 / 尖帽 / 全盔 / 光头）、手部道具（锤 / 书 / 匕 / 药瓶）、
// 以及**主色**。两套画法（战场 / 选择页立绘）共用同一批矩阵，
// 所以从选择界面进到战场，玩家能认出「这是刚才选的那个人」。
//
// 两条不能碰的公共元素：**外圈暗红**（「这是玩家」的类别标志，怪物一律没有这个环，
// 由 render.js 单独绘制）与**琥珀金点缀**（腰带 / 十字 / 帽带 / 药瓶）——
// 它们不参与「区分谁是谁」，所以不能被角色色带跑。

