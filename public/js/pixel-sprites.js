// 比任何细节都管用，而圆球画法根本表达不了。
//
// 网格分档（为什么不是一套网格到底）：像素风里「多大的东西用多大的网格」
// 是常识 —— 小怪用 16 格、Boss 用 20 格，格子数差不多意味着**每格的物理尺寸
// 随体型放大**，越大的东西颗粒越粗，气势就出来了。反过来若让小怪和 Boss
// 用同一格宽，Boss 就得画 60 格，像素感荡然无存。
//
// 字符含义见 pixel.js 的 SLOT（. 透明 / # 描边 / + 主色 / = 亮 / - 暗 / @ 更深 /
